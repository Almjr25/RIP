"""Gera o arquivo desktop sem servidor a partir da interface compartilhada."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
html = (root / 'web/index.html').read_text()
css = (root / 'web/style.css').read_text()
js = (root / 'web/app.js').read_text()
adapter = (root / 'portable/local.js').read_text()
parser = (root / 'web/receipt.js').read_text()
html = html.replace('<script src="/receipt.js" defer></script>', '')
api_line = next(line for line in js.splitlines() if line.startswith('async function api('))
js = js.replace(api_line, 'async function api(path,body){return localAPI(path,body)}')
js = js.replace("'/api/images/'+x.image", 'imageURLs.get(x.image)')
js = js.replace("'/api/images/'+r.image", 'imageURLs.get(r.image)')
js = js.replace("'/api/images/'+b.dataset.source", 'imageURLs.get(b.dataset.source)')
js = js.replace("if('serviceWorker'in navigator)navigator.serviceWorker.register('/sw.js').catch(()=>{});", '')
html = html.replace('<link rel="manifest" href="/manifest.json">', '')
html = html.replace('<link rel="icon" href="/icon.svg" type="image/svg+xml">', '')
html = html.replace('<link rel="stylesheet" href="/style.css">', '<style>'+css+'</style>')
html = html.replace('href="/"', 'href="#"')
html = html.replace('Armazenados neste dispositivo servidor.', 'Salvos neste navegador. Exporte backups.')
html = html.replace('PRIMEIRA VERSÃO · LOCAL', 'VERSÃO DESKTOP · HTML 0.2')
html = html.replace('<title>RIP ·', '<title>RIP 0.2 ·')
html = html.replace('As imagens são processadas no servidor do RIP e ficam vinculadas à compra.', 'As imagens são processadas neste computador. O OCR baixa componentes gratuitos da internet, sem enviar seus cupons.')
html = html.replace('Sem envio para APIs de OCR', 'OCR local no navegador')
html = html.replace('<div class="sidebar-bottom">', '<div class="sidebar-bottom"><button class="secondary full" id="exportBackup">Exportar backup</button><label class="secondary full" style="text-align:center;cursor:pointer">Importar backup<input type="file" id="importBackup" accept="application/json,.json" hidden></label><p>Use sempre o mesmo navegador e arquivo. Limpar os dados do navegador pode apagar o histórico. O HTML sozinho não contém suas compras.</p>')
html = html.replace('<script src="/app.js" defer></script>', '<script>'+parser+'\n'+adapter+'\n'+js+'</script>')
(root / 'RIP.html').write_text(html)
print('RIP.html gerado:', len(html.encode()), 'bytes')
